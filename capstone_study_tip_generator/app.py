from __future__ import annotations

from pathlib import Path
from typing import Tuple

import streamlit as st
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, PreTrainedModel, PreTrainedTokenizer


# -----------------------------------------------------------------------------
# Page Configuration & Caching
# -----------------------------------------------------------------------------
st.set_page_config(
    page_title="Study Tip Generator | ETMMGA304 Capstone",
    page_icon="🎓",
    layout="centered",
    initial_sidebar_state="expanded",
)


@st.cache_resource(show_spinner=False)
def load_adapted_model(model_directory: str) -> Tuple[PreTrainedTokenizer, PreTrainedModel]:
    """Loads and caches the fine-tuned GPT-2 causal language model and tokenizer."""
    tokenizer = AutoTokenizer.from_pretrained(model_directory)
    model = AutoModelForCausalLM.from_pretrained(model_directory).eval()
    return tokenizer, model


# -----------------------------------------------------------------------------
# Application Header & Sidebar
# -----------------------------------------------------------------------------
st.title("Study Tip Generator")
st.caption("AI-generated study tips for instructor review.")

# Sidebar Metadata & Governance Guide
with st.sidebar:
    st.header("Project Telemetry")
    st.markdown("**Course**: ETMMGA304 Generative AI")
    st.markdown("**Architecture**: GPT-2 (124M Parameters)")
    st.markdown("**Adaptation**: PEFT on Transformer Block 11 (`h[-1]`)")
    st.markdown("**Decoding**: Deterministic Greedy Search")
    st.divider()
    st.subheader("Pedagogical Governance")
    st.info(
        "This tool acts as an assistive drafting copilot for instructors. All synthesized "
        "tips must undergo expert pedagogical verification before student distribution."
    )

# Model Directory Verification
model_folder = Path("lab_outputs/study_tip_gpt2")
if not (model_folder / "config.json").exists():
    st.error("Run the fine-tuning step and place the exported model beside this app.")
    st.stop()

# -----------------------------------------------------------------------------
# Input Form & Generation Workflow
# -----------------------------------------------------------------------------
topic_input = st.text_input(
    "Enter a study topic",
    max_chars=120,
    help="Enter an algorithmic, mathematical, or programming concept (e.g., 'SQL joins', 'recursion', 'binary search').",
)

if st.button("Generate"):
    cleaned_topic = topic_input.strip()
    if not cleaned_topic:
        st.warning("Enter a study topic first.")
        st.stop()

    tokenizer, model = load_adapted_model(str(model_folder))
    formatted_prompt = f"Topic: {cleaned_topic}\nStudy tip:"
    inputs = tokenizer(formatted_prompt, return_tensors="pt")

    with torch.inference_mode():
        generated_tokens = model.generate(
            **inputs,
            do_sample=False,
            max_new_tokens=45,
            pad_token_id=tokenizer.eos_token_id,
        )

    # Decode continuation excluding prompt tokens
    prompt_token_count = inputs.input_ids.shape[1]
    tip_text = tokenizer.decode(
        generated_tokens[0, prompt_token_count:],
        skip_special_tokens=True,
    ).strip()

    st.write(tip_text or "No text was generated. Try a more specific topic.")
    st.caption(
        "Generated by a small fine-tuned GPT-2 model. A reviewer must check this tip "
        "before students rely on it. Do not enter personal information."
    )
